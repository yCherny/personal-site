type Props = {
  skills: SkillContent[];
};

export function SkillsetDashboard({skills}: Props) {
  const [value, setValue] = useState<string>("1");

  function filterSkills(type: string) {
    return skills
      .filter((skill) => skill.type === type)
      .sort((a, b) => b.value - a.value)
      .map((item) => {
        return {
          name: item.name,
          value: item.value,
          href: "",
          icon: function SkillIcon() {
            return (
              <Image
                height={18}
                width={18}
                alt="Skill Icon Image"
                src={item.icon}
                className="mr-3"
              />
            );
          },
        };
      });
  }

  const dataSouce = () => {
    switch (value) {
      case "2":
        return filterSkills("framework");
      case "3":
        return filterSkills("database");
      case "4":
        return filterSkills("tool");
      default:
        return filterSkills("language");
    }
  };

  const valueFormat = (value: number) => {
    switch (true) {
      case value <= 250:
        return "Novice";
      case value <= 500:
        return "Intermediate";
      case value <= 750:
        return "Advanced";
      default:
        return "Expert";
    }
  };

  return (
    <div className="rounded-lg bg-white p-5 drop-shadow-md dark:bg-[#1C1348]">
      <Flex>
        <Title className="font-bold dark:text-white">Skillset</Title>
        <Dropdown
          value={value}
          onValueChange={setValue}
          placeholder="Render mode"
          className="w-3/5 [&>button]:dark:bg-[#2C206A] [&>button]:dark:text-white [&>button]:dark:border-[#413D57] [&>button>svg]:dark:text-white"
        >
          <DropdownItem
            value="1"
            text="Pure Languages"
            icon={LanguageIcon}
            className="dark:bg-[#2C206A] dark:text-white dark:border-[#413D57]"
          />
          <DropdownItem
            value="2"
            text="Frameworks and Libraries"
            icon={FrameworkIcon}
            className="dark:bg-[#2C206A] dark:text-white dark:border-[#413D57]"
          />
          <DropdownItem
            value="3"
            text="Data Hosting and Storage"
            icon={DatabaseIcon}
            className="dark:bg-[#2C206A] dark:text-white dark:border-[#413D57]"
          />
        </Dropdown>
      </Flex>
      <BarList
        data={dataSouce()}
        valueFormatter={valueFormat}
        color="purple"
        className="mt-2 [&>.tremor-BarList-bars>*]:dark:bg-[#2C206A] [&>.tremor-BarList-bars>div>div>p]:dark:text-white [&>.text-right>div>*]:dark:text-gray-400"
      />
    </div>
  );
}
